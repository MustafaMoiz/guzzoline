const glyph = (ch) => G[ch] ?? G[ch.toUpperCase()] ?? G[' '];

export function width(text, spacing = 1) {
  let w = 0;
  for (const ch of text) w += glyph(ch)[0].length + spacing;
  return Math.max(0, w - spacing);
}

// Calls dot(x, y) for every lit dot, with y counted down from the top of the line.
export function draw(text, x, y, dot, spacing = 1) {
  for (const ch of text) {
    const g = glyph(ch);
    for (let r = 0; r < 7; r++) {
      for (let c = 0; c < g[r].length; c++) if (g[r][c] === '1') dot(x + c, y + r);
    }
    x += g[0].length + spacing;
  }
  return x;
}

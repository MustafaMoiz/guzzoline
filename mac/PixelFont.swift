  private static func glyph(_ ch: Character) -> [String] {
    glyphs[ch] ?? glyphs[Character(ch.uppercased())] ?? glyphs[" "]!
  }

  static func width(_ text: String, spacing: Int = 1) -> Int {
    max(0, text.reduce(0) { $0 + glyph($1)[0].count + spacing } - spacing)
  }

  // Calls dot(x, y) for every lit dot, y counted down from the top of the line.
  static func draw(_ text: String, x: Int, y: Int, spacing: Int = 1, dot: (Int, Int) -> Void) {
    var x = x
    for ch in text {
      let g = glyph(ch)
      for (r, row) in g.enumerated() {
        for (c, bit) in row.enumerated() where bit == "1" { dot(x + c, y + r) }
      }
      x += g[0].count + spacing
    }
  }
